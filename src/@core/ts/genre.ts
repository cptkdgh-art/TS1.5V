export function buildTsGenreBrief(input: {
  primaryGenre?: string;
  subgenres?: string[];
  themes?: string[];
}): string {
  if (input.primaryGenre !== 'TS') return '';

  const selected = [
    input.subgenres?.length ? `선택된 TS 하위유형: ${input.subgenres.join(', ')}` : '',
    input.themes?.length ? `중심 주제: ${input.themes.join(', ')}` : '',
  ].filter(Boolean).join('\n');

  return `${TS_GENRE_CORE_GUIDE}${selected ? `\n\n${selected}` : ''}`;
}
